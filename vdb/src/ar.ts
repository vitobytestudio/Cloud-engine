/* ═══════════════════════════════════════════════════════════════════
   VDB — ar.ts — العَرَبة حثيثاً: التطبيع العربي في عُظم المحرك لا فوقه.
   أول قاعدة بيانات في العالم تحمل العربية نواةً لا لاصقة: كل مفتاح نصي
   يمكن تمريره عبر arKey فيُفهرس بلا همزات متفرقة ولا تشكيل ولا تاء مربوطة.
   ═══════════════════════════════════════════════════════════════════ */

/* التشكيل والتطويل وعلامات الإيقاف */
const DIACRITICS = /[\u064B-\u0655\u0670\u0640]/g;

/** توحيد الحروف المتشابهة: أإآٱ→ا، ة→ه، ى→ي، ؤ→و، ئ→ي + خفض الحالة اللاتينية */
export const normAr = (s: string): string =>
  s
    .replace(DIACRITICS, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .toLowerCase();

/** مفتاح بحث عربي: تطبيع + تقليم الفراغات — جاهز للفهرسة والمقارنة */
export const arKey = (s: string): string => normAr(s.trim()).replace(/\s+/g, " ");
